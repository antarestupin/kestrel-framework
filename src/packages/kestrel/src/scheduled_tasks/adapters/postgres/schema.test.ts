import { getTableConfig } from "drizzle-orm/pg-core";
import { describe, expect, it } from "vitest";

import { getFrameworkDatabaseTableKeys } from "../../../db/framework_table.js";
import { scheduledTaskRuns, scheduledTaskStates } from "./schema.js";

/** These migration-facing contracts use the actual exported schema, not the temporary adapter fixture. */
describe("scheduled-task PostgreSQL schema contracts", () => {
  it("keeps SQL mappings and framework migration provenance valid", () => {
    expect(getFrameworkDatabaseTableKeys({ scheduledTaskRuns, scheduledTaskStates })).toEqual(new Set([
      JSON.stringify(["scheduled_tasks", "run"]), JSON.stringify(["scheduled_tasks", "state"]),
    ]));
    for (const table of [scheduledTaskStates, scheduledTaskRuns]) {
      const config = getTableConfig(table);
      // SQL recovery clauses address snake-case storage fields, not implicit camel-case fallback names.
      expect(new Set(config.columns.map((column) => column.name)).size).toBe(config.columns.length);
      for (const column of config.columns) expect(column.name).toMatch(/^[a-z][a-z0-9_]*$/u);
      for (const index of config.indexes) {
        // Explicit empty SQL identifiers are invalid; autogenerated labels remain permitted.
        if (index.config.name !== undefined) expect(index.config.name.length).toBeGreaterThan(0);
      }
    }
  });

  it("retains singular qualified tables and primary ownership identities", () => {
    expect(getTableConfig(scheduledTaskStates)).toMatchObject({ name: "state", schema: "scheduled_tasks" });
    expect(getTableConfig(scheduledTaskRuns)).toMatchObject({ name: "run", schema: "scheduled_tasks" });
    expect(scheduledTaskStates.taskId.primary).toBe(true);
    expect(scheduledTaskRuns.reservationToken.primary).toBe(true);
    expect(scheduledTaskRuns.taskId.notNull).toBe(true);
    expect(scheduledTaskRuns.trigger.notNull).toBe(true);
  });

  it("preserves safe initial controls, attempts and timezone-aware lease dates", () => {
    expect(scheduledTaskStates.paused.default).toBe(false);
    expect(scheduledTaskStates.paused.notNull).toBe(true);
    expect(scheduledTaskRuns.attempt.default).toBe(1);
    expect(scheduledTaskRuns.attempt.notNull).toBe(true);
    for (const column of [scheduledTaskStates.nextScheduledAt, scheduledTaskStates.manualRunRequestedAt,
      scheduledTaskStates.lastStartedAt, scheduledTaskStates.lastCompletedAt, scheduledTaskStates.updatedAt,
      scheduledTaskRuns.scheduledAt, scheduledTaskRuns.reservedAt, scheduledTaskRuns.expiresAt]) {
      expect(column.getSQLType()).toBe("timestamp with time zone");
      expect(column.dataType).toBe("date");
    }
    expect(scheduledTaskStates.updatedAt.hasDefault).toBe(true);
    expect(scheduledTaskStates.updatedAt.notNull).toBe(true);
    expect(scheduledTaskRuns.reservedAt.hasDefault).toBe(true);
    expect(scheduledTaskRuns.reservedAt.notNull).toBe(true);
    expect(scheduledTaskRuns.scheduledAt.notNull).toBe(true);
    expect(scheduledTaskRuns.expiresAt.notNull).toBe(true);
  });

  it("indexes due-state and task-expiry access paths without pinning index labels", () => {
    const columns = (table: typeof scheduledTaskStates | typeof scheduledTaskRuns) => getTableConfig(table).indexes.map((index) => index.config.columns.map((column) => "name" in column ? column.name : undefined));
    expect(columns(scheduledTaskStates)).toContainEqual(["paused", "next_scheduled_at"]);
    expect(columns(scheduledTaskRuns)).toContainEqual(["task_id", "expires_at"]);
  });
});
